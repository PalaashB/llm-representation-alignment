"""A second prompt bank: multi-item answers, scored conjunctively.

Why this exists
---------------
The original bank (`common.prompts`) asks for one fact and accepts a 3-5 token
answer. That makes it a bad instrument for a *latency* experiment, in two ways
that both flatter the small model:

1. **Decode barely happens.** At 3-5 generated tokens against a ~40 token
   prompt, end-to-end time is prefill, and prefill is the part stitching does
   not help (the `warm` mode pays for a full large-model prefill on purpose).
   A per-token speedup measured on a forced 32-step run is real, but it is not
   what a user of that bank would feel.
2. **The models tie.** Llama-1B answers "capital of New Zealand" as well as
   Llama-3B does, so there is no accuracy for a stitch to *recover* — the
   headroom between the two models is what a stitch spends its extra layers on,
   and on short factual recall there is almost none.

This bank fixes both. Every question asks for a set — three capitals, the four
DNA bases, the nine countries bordering Germany — so

* answers run 20-60 tokens, which is decode-dominated, and
* `common.scoring.is_correct_all` requires *every* item, which is where a small
  model actually falls behind: it reliably names the famous two thirds of a set
  and drops the rest.

Composition (135 prompts): capitals of country triples, land borders, chemical
symbols and atomic numbers, canonical science sets, geography sets, history and
civics sets, sports and arts sets, small arithmetic sets, and event-year pairs.
The facts are all textbook-stable and order-independent, and each required item
carries its own alias list so wording and spelling variants score the same.

Item shape:
    id, category, question, answers (canonical string, for display),
    requires  — list of alias groups, ALL of which must appear to score.
"""

